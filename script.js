function applyTranslations(locale, i18nTextElements, i18nPlaceholderElements, i18nAriaElements, langButtons, htmlElement) {
  htmlElement.lang = locale;
  i18nTextElements.forEach((node) => {
    const key = node.dataset.i18n;
    if (translations[locale][key]) {
      node.textContent = translations[locale][key];
    }
  });
  i18nPlaceholderElements.forEach((input) => {
    const key = input.dataset.i18nPlaceholder;
    if (translations[locale][key]) {
      input.placeholder = translations[locale][key];
    }
  });
  i18nAriaElements.forEach((node) => {
    const key = node.dataset.i18nAria;
    if (translations[locale][key]) {
      node.setAttribute('aria-label', translations[locale][key]);
    }
  });
  langButtons.forEach((button) => {
    button.classList.toggle('active', button.dataset.lang === locale);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const preloader = document.getElementById('preloader');
  const navToggle = document.getElementById('navToggle');
  const mainNav = document.getElementById('mainNav');
  const reservationForm = document.getElementById('reservationForm');
  const htmlElement = document.documentElement;
  const langButtons = document.querySelectorAll('.lang-btn');
  const i18nTextElements = document.querySelectorAll('[data-i18n]');
  const i18nPlaceholderElements = document.querySelectorAll('[data-i18n-placeholder]');
  const i18nAriaElements = document.querySelectorAll('[data-i18n-aria]');
  const savedLang = localStorage.getItem('transfercr-lang') || 'es';
  let currentLang = savedLang;

  setTimeout(() => {
    preloader.classList.add('loaded');
    preloader.style.opacity = '0';
    preloader.style.visibility = 'hidden';
  }, 800);

  const setLanguage = (language) => {
    const locale = translations[language] ? language : 'es';
    currentLang = locale;
    localStorage.setItem('transfercr-lang', locale);
    applyTranslations(locale, i18nTextElements, i18nPlaceholderElements, i18nAriaElements, langButtons, htmlElement);
  };

  setLanguage(savedLang);

  let emailjsReady = false;
  const emailjsLoader = new Promise((resolve, reject) => {
    const initializeEmailJS = () => {
      if (window.emailjs) {
        emailjs.init('vnDmphO2tGdkjDYgN');
        emailjsReady = true;
        resolve();
      } else {
        reject(new Error('EmailJS SDK no cargado.'));
      }
    };

    if (window.emailjs) {
      initializeEmailJS();
      return;
    }

    const script = document.createElement('script');
    script.type = 'text/javascript';
    script.src = 'https://cdn.jsdelivr.net/npm/emailjs-com@3.2.0/dist/email.min.js';
    script.onload = initializeEmailJS;
    script.onerror = () => reject(new Error('No se pudo cargar EmailJS.'));
    document.body.appendChild(script);
  });

  emailjsLoader.catch((error) => {
    console.warn(error.message, error);
  });

  navToggle.addEventListener('click', () => {
    mainNav.classList.toggle('active');
  });

  langButtons.forEach((button) => {
    button.addEventListener('click', () => {
      setLanguage(button.dataset.lang);
    });
  });

  reservationForm.addEventListener('submit', (event) => {
    event.preventDefault();
    const name = reservationForm.name.value.trim();
    const destination = reservationForm.destination.value.trim();
    const date = reservationForm.date.value;
    const passengers = reservationForm.passengers.value;
    const email = reservationForm.email.value.trim();
    const phone = reservationForm.phone.value.trim();
    const comments = reservationForm.comments.value.trim();

    if (!name || !destination || !date || !passengers || !email || !phone) {
      alert(translations[currentLang].validationError);
      return;
    }

    if (!emailjsReady) {
      alert('EmailJS aún no está listo. Por favor espera un momento e inténtalo nuevamente.');
      return;
    }

    emailjsLoader
      .then(() => {
        return emailjs.send('service_z02ylxk', 'template_vxxxuy7', {
          from_name: name,
          destination,
          date,
          passengers,
          email,
          phone,
          comments,
          message: `Reserva con TransferCR:\nNombre: ${name}\nDestino: ${destination}\nFecha: ${date}\nPasajeros: ${passengers}\nEmail: ${email}\nTeléfono: ${phone}\nComentarios: ${comments}`
        });
      })
      .then(() => {
        alert(translations[currentLang].formSentSuccess);
        reservationForm.reset();
      })
      .catch((error) => {
        console.error('EmailJS error:', error);
        alert(translations[currentLang].formSentError);
      });
  });
});

function scrollToSection(id) {
  const section = document.getElementById(id);
  if (section) {
    section.scrollIntoView({ behavior: 'smooth', block: 'start' });
  }
}
